function translateScenarioProseToVi(text: string): string {
  if (text.length < 10 || text.startsWith("/") || text.startsWith("{") || /^[A-Za-z0-9_.-]+$/.test(text) || !SCENARIO_PROSE_GUARD.test(text)) {
    return text;
  }
  let out = text;
  for (const [pattern, replacement] of SCENARIO_PROSE_RULES) {
    out = out.replace(pattern, replacement);
  }
  if (out !== text) {
    out = out
      .replace(/\bacross\b/gi, "trên")
      .replace(/\band\b/gi, "và")
      .replace(/\bwith\b/gi, "kèm")
      .replace(/\bthen\b/gi, "sau đó");
  }
  return out;
}

export function translateText(text: string, locale: Locale): string {
  if (locale === "en") return text;
  return translateStringToVi(text);
}

export function translateStringToVi(raw: string): string {
  const trimmed = raw.trim();
  if (!trimmed) return raw;

  // 1. Exact match
  const exact = EXACT_VI_DICTIONARY[trimmed];
  if (exact) {
    return raw.replace(trimmed, exact);
  }

  // 2. Trailing punctuation checks
  if (trimmed.endsWith(":")) {
    const base = trimmed.slice(0, -1).trim();
    if (EXACT_VI_DICTIONARY[base]) {
      return raw.replace(trimmed, EXACT_VI_DICTIONARY[base] + ":");
    }
  }

  if (trimmed.endsWith("...") || trimmed.endsWith("…")) {
    const base = trimmed.replace(/\.{3}$|…$/, "").trim();
    if (EXACT_VI_DICTIONARY[base]) {
      return raw.replace(trimmed, EXACT_VI_DICTIONARY[base] + "…");
    }
  }

  if (trimmed.endsWith("→") || trimmed.endsWith("->")) {
    const base = trimmed.replace(/→$|->$/, "").trim();
    if (EXACT_VI_DICTIONARY[base]) {
      return raw.replace(trimmed, EXACT_VI_DICTIONARY[base] + " →");
    }
  }

  if (trimmed.endsWith("?")) {
    const base = trimmed.slice(0, -1).trim();
    if (EXACT_VI_DICTIONARY[base]) {
      return raw.replace(trimmed, EXACT_VI_DICTIONARY[base] + "?");
    }
  }

  // 3. Numbered prefix or version suffix decomposition (e.g. "1. Catalog & Inventory", "Scenario Name (v1)")
  const numberedMatch = /^(\d+)\.\s+(.+)$/.exec(trimmed);
  if (numberedMatch) {
    const innerTranslated = translateStringToVi(numberedMatch[2]!);
    if (innerTranslated !== numberedMatch[2]) {
      return raw.replace(trimmed, `${numberedMatch[1]}. ${innerTranslated}`);
    }
  }

  const versionSuffixMatch = /^(.+)\s+\(v(\d+)\)$/i.exec(trimmed);
  if (versionSuffixMatch) {
    const innerTranslated = translateStringToVi(versionSuffixMatch[1]!);
    if (innerTranslated !== versionSuffixMatch[1]) {
      return raw.replace(trimmed, `${innerTranslated} (v${versionSuffixMatch[2]})`);
    }
  }

  // 4. Dynamic pattern matching
  for (const [regex, replacement] of PATTERN_REPLACEMENTS) {
    if (regex.test(trimmed)) {
      return raw.replace(trimmed, trimmed.replace(regex, replacement));
    }
  }

  // 5. Scenario & architectural prose translation (AI summaries, stage chips, step rationales)
  const proseTranslated = translateScenarioProseToVi(trimmed);
  if (proseTranslated !== trimmed) {
    return raw.replace(trimmed, proseTranslated);
  }

  return raw;
}

const LocaleContext = createContext<LocaleContextValue>({
  locale: "en",
  setLocale: () => {},
  toggleLocale: () => {},
  t: (en) => en,
  tr: (text) => text,
});

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved === "vi" || saved === "en") {
        setLocaleState(saved);
      }
    } catch {
      // ignore storage errors
    }
  }, []);

  const setLocale = (next: Locale) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
      document.documentElement.lang = next;
    } catch {
      // ignore
    }
  };

  const toggleLocale = () => setLocale(locale === "en" ? "vi" : "en");

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      setLocale,
      toggleLocale,
      t: (enText: string, viText?: string) => {
        if (locale === "en") return enText;
        return viText ?? translateStringToVi(enText);
      },
      tr: (text: string) => {
        if (locale === "en") return text;
        return translateStringToVi(text);
      },
    }),
    [locale],
  );

  return (
    <LocaleContext.Provider value={value}>
      <AutoDomTranslator locale={locale} />
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  return useContext(LocaleContext);
}

interface TrackedTextRecord {
  original: string;
  lastRendered: string;
}
const originalTextMap = new WeakMap<Node, TrackedTextRecord>();
const originalAttrMap = new WeakMap<Element, Map<string, TrackedTextRecord>>();
let isApplyingDomTranslation = false;

function shouldSkipElement(el: Element | null): boolean {
  if (!el) return true;
  const tag = el.tagName;
  if (tag === "SCRIPT" || tag === "STYLE" || tag === "CODE" || tag === "PRE" || tag === "TEXTAREA" || tag === "SVG" || tag === "PATH") {
    return true;
  }
  if (el.closest("code, pre, script, style, textarea, [data-no-translate]")) {
    return true;
  }
  return false;
}

function applyDomTranslation(root: Node, locale: Locale) {
  if (typeof document === "undefined" || isApplyingDomTranslation) return;
  isApplyingDomTranslation = true;
  try {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let current: Node | null = root.nodeType === 3 ? root : walker.nextNode();
    while (current) {
      const parent = current.parentElement;
      if (!shouldSkipElement(parent)) {
        const currentVal = current.nodeValue ?? "";
        let record = originalTextMap.get(current);
        if (!record) {
          record = { original: currentVal, lastRendered: currentVal };
          originalTextMap.set(current, record);
        } else if (currentVal !== record.lastRendered && currentVal !== record.original) {
          // React dynamically updated this text node! Update the baseline original text.
          record.original = currentVal;
        }
        const nextVal = locale === "vi" ? translateStringToVi(record.original) : record.original;
        if (currentVal !== nextVal) {
          current.nodeValue = nextVal;
        }
        record.lastRendered = nextVal;
      }
      current = walker.nextNode();
    }

    if (root instanceof Element || root instanceof Document) {
      const container = root instanceof Document ? root.body : root;
      const elements = [...(root instanceof Element ? [root] : []), ...(container?.querySelectorAll?.("[placeholder], [title], [aria-label]") ?? [])];
      elements?.forEach((el) => {
        if (shouldSkipElement(el)) return;
        let attrMap = originalAttrMap.get(el);
        if (!attrMap) {
          attrMap = new Map();
          originalAttrMap.set(el, attrMap);
        }
        for (const attr of ["placeholder", "title", "aria-label"]) {
          const val = el.getAttribute(attr);
          if (!val) continue;
          let rec = attrMap.get(attr);
          if (!rec) {
            rec = { original: val, lastRendered: val };
            attrMap.set(attr, rec);
          } else if (val !== rec.lastRendered && val !== rec.original) {
            rec.original = val;
          }
          const nextVal = locale === "vi" ? translateStringToVi(rec.original) : rec.original;
          if (val !== nextVal) {
            el.setAttribute(attr, nextVal);
          }
          rec.lastRendered = nextVal;
        }
      });
    }
  } finally {
    isApplyingDomTranslation = false;
  }
}

function AutoDomTranslator({ locale }: { locale: Locale }) {
  useEffect(() => {
    if (typeof document === "undefined" || !document.body) return;
    applyDomTranslation(document.body, locale);
    if (locale !== "vi") return;

    let rafId = 0;
    const pending = new Set<Node>();
    const observation = {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "title", "aria-label"],
    };
    const collect = (records: MutationRecord[]) => {
      for (const record of records) {
        if (record.type === "characterData") {
          const tracked = originalTextMap.get(record.target);
          if (!tracked || record.target.nodeValue !== tracked.lastRendered) pending.add(record.target);
        } else if (record.type === "attributes" && record.target instanceof Element) {
          const attribute = record.attributeName;
          if (!attribute) continue;
          const tracked = originalAttrMap.get(record.target)?.get(attribute);
          if (!tracked || record.target.getAttribute(attribute) !== tracked.lastRendered) pending.add(record.target);
        } else {
          record.addedNodes.forEach((node) => pending.add(node));
        }
      }
    };
    const observer = new MutationObserver((records) => {
      collect(records);
      if (rafId || !pending.size) return;
      rafId = requestAnimationFrame(() => {
        rafId = 0;
        collect(observer.takeRecords());
        // Translation writes must not schedule another pass over the same text.
        observer.disconnect();
        try {
          for (const node of pending) {
            if (!node.isConnected) continue;
            let parent = node.parentNode;
            while (parent && !pending.has(parent)) parent = parent.parentNode;
            if (!parent) applyDomTranslation(node, "vi");
          }
        } finally {
          pending.clear();
          if (document.body) observer.observe(document.body, observation);
        }
      });
    });
    observer.observe(document.body, observation);
    return () => {
      if (rafId) cancelAnimationFrame(rafId);
      pending.clear();
      observer.disconnect();
    };
  }, [locale]);

  return null;
}

