  private advanceJob(job: AnalysisJob): AnalysisJob {
    if (["completed", "failed"].includes(job.status)) return job;
    job.progress = Math.min(
      100,
      Math.floor((Date.now() - (this.started.get(job.id) ?? Date.now())) / 50),
    );
    job.status =
      job.progress >= 100
        ? this.scenario === "analysis-failed"
          ? "failed"
          : "completed"
        : "processing";
    job.message =
      job.status === "failed"
        ? "Sample analysis failed. Retry with the validated snapshot."
        : job.status === "completed"
          ? "Sample analysis completed; review evidence coverage."
          : "Simulating source analysis";
    if (job.status === "completed") {
      const snapshot = this.find(this.snapshots, (s) => s.id === job.snapshotId);
      const base = this.models[0];
      if (!base) throw new ApiError("contract");
      const model = structuredClone(base);
      model.id = crypto.randomUUID();
      model.projectId = job.projectId;
      model.snapshotId = job.snapshotId;
      model.revision =
        Math.max(
          0,
          ...this.models.filter((m) => m.projectId === job.projectId).map((m) => m.revision),
        ) + 1;
      model.label = `Source analysis · revision ${model.revision}`;
      if (!snapshot.evidenceComplete)
        model.elements.forEach((e) =>
          e.evidence.forEach((v) => {
            v.complete = false;
          }),
        );
      this.models.push(model);
      job.modelId = model.id;
      const project = this.find(this.projects, (p) => p.id === job.projectId);
      project.services = model.elements.length;
      project.status = "ready";
    }
    if (job.status === "failed")
      this.find(this.projects, (p) => p.id === job.projectId).status = "failed";
    return job;
  }
  private advanceSession(session: RuntimeSession) {
    if (
      session.status === "running" &&
      Date.now() - (this.started.get(session.id) ?? Date.now()) >= 6000
    ) {
      session.status = this.scenario === "runtime-failed" ? "failed" : "completed";
      session.outcome = session.status === "failed" ? "failed" : "passed";
      session.events.push({
        at: new Date().toISOString(),
        message: `Sample scenario ${session.outcome}; ${session.status === "failed" ? "trace unavailable" : "one sample trace available"}`,
      });
      if (session.status === "completed")
        session.traces.push({
          id: crypto.randomUUID(),
          from: "gateway",
          to: "orders",
          durationMs: 42,
          uncertain: true,
        });
    }
    return session;
  }
