"use client";
import { useEffect, useMemo, useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import { useApi, useApiQuery } from "@/hooks/use-api";
import type { ArchitecturalModel } from "@/types/domain";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { SelectField } from "@/components/shared/forms";
import { DrawioEditor } from "./drawio-editor";
import { SearchableThreeESelect } from "./three-e-searchable-select";
import type { DrawioTheme } from "@/lib/drawio/rules";
import {
  buildAutoSequenceInteraction,
  buildFlowCompactContext,
  detectSequenceFlows,
  extractInteractionFromDrawioXml,
  interactionToDrawioXml,
  synthesizeAiSequenceEnrichment,
  type InteractionDocument,
  type SequenceAiEnrichment,
  type SequenceGranularityLevel,
} from "./scenario-design";
import {
  resolveSequenceSelectionContext,
  type SequenceSelectionContext,
} from "./three-e-content";

const clientEnrichmentCache = new Map<string, SequenceAiEnrichment>();

export function DesignedScenario({
  model,
  onSelect,
  onSelectSequence,
  initialInteraction,
  onConsumedInitialInteraction,
  theme: externalTheme,
  onThemeChange,
}: {
  model: ArchitecturalModel;
  selectedId?: string | null | undefined;
  onSelect: (id: string) => void;
  onSelectSequence?:
    | ((id: string | null, seqCtx: SequenceSelectionContext | null) => void)
    | undefined;
  initialInteraction?: InteractionDocument | null | undefined;
  onConsumedInitialInteraction?: (() => void) | undefined;
  theme?: DrawioTheme | undefined;
  onThemeChange?: ((theme: DrawioTheme) => void) | undefined;
}) {
  const api = useApi(),
    cache = useQueryClient();

  const [level, setLevel] = useState<SequenceGranularityLevel>("MACRO");
  const [selectedServiceId, setSelectedServiceId] = useState<string>("");
  const [selectedFlowId, setSelectedFlowId] = useState<string>("");
  const [internalTheme, setInternalTheme] = useState<DrawioTheme>(externalTheme ?? "clean");
  const theme = externalTheme ?? internalTheme;
  const setTheme = (next: DrawioTheme) => {
    setInternalTheme(next);
    onThemeChange?.(next);
  };
  const [copiedOverride, setCopiedOverride] = useState<InteractionDocument | null>(null);
  const [forceAutoGenerated, setForceAutoGenerated] = useState<boolean>(false);
  const [aiEnrichment, setAiEnrichment] = useState<SequenceAiEnrichment | null>(null);
  const [flowTitleById, setFlowTitleById] = useState<Record<string, string>>({});
  const [error, setError] = useState<string>("");

  // Services that have internal components for Level 2 (Micro)
  const microServices = useMemo(() => {
    const allMicro = detectSequenceFlows(model, { level: "MICRO" });
    const byService = new Map<string, { id: string; name: string; flowCount: number }>();
    for (const flow of allMicro) {
      if (!flow.serviceId || !flow.serviceName) continue;
      const cur = byService.get(flow.serviceId);
      if (cur) cur.flowCount += 1;
      else byService.set(flow.serviceId, { id: flow.serviceId, name: flow.serviceName, flowCount: 1 });
    }
    return [...byService.values()].sort(
      (a, b) => b.flowCount - a.flowCount || a.name.localeCompare(b.name),
    );
  }, [model]);

  const activeServiceId =
    level === "MICRO"
      ? (microServices.find((s) => s.id === selectedServiceId)?.id ?? microServices[0]?.id ?? null)
      : null;

  const availableFlows = useMemo(
    () =>
      detectSequenceFlows(model, {
        level,
        serviceId: level === "MICRO" ? activeServiceId : null,
      }),
    [model, level, activeServiceId],
  );

  const activeFlow = useMemo(
    () => availableFlows.find((f) => f.flowId === selectedFlowId) ?? availableFlows[0] ?? null,
    [availableFlows, selectedFlowId],
  );

  useEffect(() => {
    if (!initialInteraction) return;
    setCopiedOverride(initialInteraction);
    setForceAutoGenerated(false);
    onConsumedInitialInteraction?.();
  }, [initialInteraction, onConsumedInitialInteraction]);

  useEffect(() => {
    if (!activeFlow || copiedOverride) {
      setAiEnrichment(null);
      return;
    }
    const compact = buildFlowCompactContext(model, activeFlow);
    const localFallback = synthesizeAiSequenceEnrichment(model, activeFlow);
    const cached = clientEnrichmentCache.get(compact.contextHash);
    if (cached) {
      setAiEnrichment(cached);
      if (cached.flowTitle) {
        setFlowTitleById((prev) =>
          prev[activeFlow.flowId] === cached.flowTitle
            ? prev
            : { ...prev, [activeFlow.flowId]: cached.flowTitle! },
        );
      }
      return;
    }
    setAiEnrichment(localFallback);

    let cancelled = false;
    fetch("/api/ai-diagram-semantics", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ context: compact, fallback: localFallback }),
    })
      .then((res) => (res.ok ? res.json() : null))
      .then((data: { enrichment?: SequenceAiEnrichment } | null) => {
        if (cancelled || !data?.enrichment) return;
        clientEnrichmentCache.set(compact.contextHash, data.enrichment);
        setAiEnrichment(data.enrichment);
        if (data.enrichment.flowTitle) {
          setFlowTitleById((prev) => ({
            ...prev,
            [activeFlow.flowId]: data.enrichment!.flowTitle!,
          }));
        }
      })
      .catch(() => {
        // Keep local AST-skeleton fallback on offline/error
      });
    return () => {
      cancelled = true;
    };
  }, [activeFlow, copiedOverride, model]);

  const viewId = copiedOverride
    ? copiedOverride.interactionId
    : (activeFlow?.viewId ?? "scenarios:auto:default");

  const saved = useApiQuery(
    "architectureDocument",
    { modelId: model.id, viewId },
    { enabled: api.mode === "backend" && !!activeFlow },
  );

  const autoDoc = useMemo(() => {
    if (copiedOverride) return copiedOverride;
    if (!activeFlow) return null;
    return buildAutoSequenceInteraction(model, activeFlow, aiEnrichment);
  }, [copiedOverride, activeFlow, model, aiEnrichment]);

  const hasValidSavedXml = Boolean(
    !forceAutoGenerated &&
      saved.data?.xml &&
      saved.data.xml.includes('mavisAutoSeqVersion="5"'),
  );

  // If backend has a valid v5 saved layout for this auto flow, preserve its horizontal lifeline layoutX
  const effectiveDoc = useMemo(() => {
    if (!autoDoc) return null;
    if (!hasValidSavedXml || !saved.data?.xml) return autoDoc;
    const extracted = extractInteractionFromDrawioXml(saved.data.xml, model);
    if (extracted && extracted.document.messages.length > 0) {
      return extracted.document;
    }
    return autoDoc;
  }, [autoDoc, hasValidSavedXml, saved.data?.xml, model]);

  const generatedXml = useMemo(() => {
    if (!autoDoc) return "";
    try {
      return interactionToDrawioXml(autoDoc, model);
    } catch {
      return "";
    }
  }, [autoDoc, model]);

  const activeXml = useMemo(() => {
    if (hasValidSavedXml && saved.data?.xml) {
      return saved.data.xml;
    }
    return generatedXml;
  }, [hasValidSavedXml, saved.data?.xml, generatedXml]);

  const [activeSeqItemId, setActiveSeqItemId] = useState<string>("");

  function selectSequenceItem(itemId: string) {
    setActiveSeqItemId(itemId);
    if (!effectiveDoc) return;
    const seqCtx = resolveSequenceSelectionContext(effectiveDoc, itemId);
    let canonicalTargetId = itemId;
    if (
      seqCtx.itemKind === "participant" &&
      seqCtx.modelElementId &&
      seqCtx.resolutionStatus === "RESOLVED"
    ) {
      canonicalTargetId = seqCtx.modelElementId;
    } else if (
      seqCtx.itemKind === "message" &&
      seqCtx.sourceRelationshipIds &&
      seqCtx.sourceRelationshipIds.length === 1
    ) {
      canonicalTargetId = seqCtx.sourceRelationshipIds[0]!;
    }
    if (onSelectSequence) {
      onSelectSequence(canonicalTargetId, seqCtx);
    } else {
      onSelect(canonicalTargetId);
    }
  }

  async function saveXmlDocument(contentXml: string) {
    if (!contentXml || !saved.data || saved.error) return;
    setError("");
    try {
      const result = await api.execute("saveArchitectureDocument", {
        modelId: model.id,
        viewId,
        expectedRevision: saved.data.revision,
        xml: contentXml,
      });
      cache.setQueryData(["api", "architectureDocument", { modelId: model.id, viewId }], result);
      setForceAutoGenerated(false);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Scenario could not be saved.");
      throw err;
    }
  }

  return (
    <div className="space-y-2.5">
      <div className="space-y-2.5 rounded-xl border bg-card p-3">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="text-xs font-medium text-muted-foreground mr-0.5">Scope:</span>
            <Button
              type="button"
              size="sm"
              className="h-7 px-2.5 text-xs"
              variant={level === "MACRO" && !copiedOverride ? "default" : "outline"}
              onClick={() => {
                setCopiedOverride(null);
                setLevel("MACRO");
                setSelectedFlowId("");
                setForceAutoGenerated(false);
                onSelectSequence?.(null, null);
              }}
            >
              System · Macro
            </Button>
            <Button
              type="button"
              size="sm"
              className="h-7 px-2.5 text-xs"
              variant={level === "MICRO" && !copiedOverride ? "default" : "outline"}
              onClick={() => {
                setCopiedOverride(null);
                setLevel("MICRO");
                setSelectedFlowId("");
                setForceAutoGenerated(false);
                onSelectSequence?.(null, null);
              }}
            >
              Service · Micro
            </Button>
            {copiedOverride && (
              <Badge variant="secondary">
                Viewing copied runtime trace: {copiedOverride.name}
              </Badge>
            )}
          </div>
        </div>

        {/* Service & Auto-Detected Flow Selectors */}
        {!copiedOverride && (
          <div
            className={
              level === "MICRO"
                ? "grid gap-3 sm:grid-cols-2 items-end"
                : "grid gap-3 sm:grid-cols-1 items-end"
            }
          >
            {level === "MICRO" && (
              <SelectField
                label="Service"
                value={activeServiceId ?? ""}
                onChange={(nextSvc) => {
                  setSelectedServiceId(nextSvc);
                  setSelectedFlowId("");
                  setForceAutoGenerated(false);
                  onSelectSequence?.(null, null);
                }}
                options={microServices.map((s) => ({
                  value: s.id,
                  label: s.name,
                }))}
              />
            )}
            {availableFlows.length > 0 && (
              <SelectField
                label="Sequence flow"
                value={activeFlow?.flowId ?? ""}
                onChange={(nextFlowId) => {
                  setSelectedFlowId(nextFlowId);
                  setForceAutoGenerated(false);
                  onSelectSequence?.(null, null);
                }}
                options={availableFlows.map((f) => ({
                  value: f.flowId,
                  label: flowTitleById[f.flowId] ?? f.title,
                }))}
              />
            )}
          </div>
        )}

        {/* Flow Summary Banner */}
        {!copiedOverride && activeFlow && (
          <div
            className="flex flex-wrap items-center justify-between gap-2 rounded-lg border bg-primary/5 px-3 py-2 text-xs"
            data-testid="sequence-ai-topdown-flow-banner"
          >
            <div className="space-y-0.5">
              <div className="flex flex-wrap items-center gap-1.5">
                <span className="inline-flex items-center rounded bg-primary/15 px-1.5 py-0.5 text-[10px] font-semibold text-primary">
                  Flow summary
                </span>
                <span className="font-semibold text-foreground">
                  {aiEnrichment?.flowTitle || activeFlow.title}
                </span>
              </div>
              <p className="text-muted-foreground leading-relaxed">
                {aiEnrichment?.flowSummary || activeFlow.description}
              </p>
            </div>
          </div>
        )}

        {/* Interactive Elements & Connections Dropdowns for 3E Inspection */}
        {effectiveDoc && effectiveDoc.participants.length > 0 && (
          <div className="grid gap-3 border-t pt-3 sm:grid-cols-2">
            <SearchableThreeESelect
              label="Element to explore"
              placeholder="Select or search elements…"
              selectedValue={activeSeqItemId}
              onSelect={selectSequenceItem}
              options={effectiveDoc.participants.map((p, idx) => ({
                value: p.participantId,
                badge: p.elementType ?? "LIFELINE",
                label: `${idx + 1}. :${p.name}`,
                sublabel: `Status: ${p.resolutionStatus}`,
              }))}
            />
            <SearchableThreeESelect
              label="Connection to explore"
              placeholder="Select or search connections…"
              selectedValue={activeSeqItemId}
              onSelect={selectSequenceItem}
              options={effectiveDoc.messages.map((msg, i) => {
                const fromPart = effectiveDoc.participants.find(
                  (p) => p.participantId === msg.fromParticipantId,
                );
                const toPart = effectiveDoc.participants.find(
                  (p) => p.participantId === msg.toParticipantId,
                );
                const senderLabel =
                  msg.fromParticipantId === "__FOUND__"
                    ? "● [Found]"
                    : (fromPart?.name ?? msg.fromParticipantId);
                return {
                  value: msg.messageId,
                  badge: msg.messageSort,
                  label: `${i + 1}. ${senderLabel} → ${toPart?.name ?? msg.toParticipantId}`,
                  sublabel: msg.label,
                };
              })}
            />
          </div>
        )}

        {error && (
          <p role="alert" className="text-sm text-destructive">
            {error}
          </p>
        )}

        {!effectiveDoc && (
          <p role="status" className="text-sm text-muted-foreground">
            No source-supported sequence flows were detected for this scope.
          </p>
        )}
      </div>

      {activeXml && effectiveDoc && (
        <DrawioEditor
          key={`${model.id}:${viewId}`}
          modelId={model.id}
          diagramId={viewId}
          title={`Sequence · ${effectiveDoc.name}`}
          notation="UML_SEQUENCE"
          level="SCENARIO"
          scope={viewId}
          theme={theme}
          onThemeChange={setTheme}
          xml={activeXml}
          generatedXml={generatedXml || activeXml}
          preferProvidedXml={hasValidSavedXml}
          autoSaveWhenReady={Boolean(
            !copiedOverride && saved.data && !hasValidSavedXml && !saved.error && generatedXml,
          )}
          onSave={saveXmlDocument}
        />
      )}
    </div>
  );
}

