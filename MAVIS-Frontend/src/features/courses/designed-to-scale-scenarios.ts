export function getScenarioForLessonOrLab(
  modulePosition?: number | null | undefined,
  codeOrTitle?: string | null | undefined,
): ConceptScenario {
  if (codeOrTitle) {
    const normalized = codeOrTitle.toLowerCase();
    for (const [code, scenario] of Object.entries(DESIGNED_TO_SCALE_SCENARIOS)) {
      if (normalized === code || normalized.includes(`(${code})`) || normalized.includes(code)) {
        return scenario;
      }
    }
    if (normalized.includes("shared db") || normalized.includes("bounded context") || normalized.includes("ddd")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-02"]!;
    }
    if (normalized.includes("reverse bfs") || normalized.includes("feign") || normalized.includes("lan truyền")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-04"]!;
    }
    if (normalized.includes("eureka")) return DESIGNED_TO_SCALE_SCENARIOS["java-05"]!;
    if (normalized.includes("gateway")) return DESIGNED_TO_SCALE_SCENARIOS["java-06"]!;
    if (normalized.includes("circuit breaker") || normalized.includes("resilience4j")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-07"]!;
    }
    if (normalized.includes("bulkhead") || normalized.includes("retry")) return DESIGNED_TO_SCALE_SCENARIOS["java-08"]!;
    if (normalized.includes("kafka") || normalized.includes("rabbitmq") || normalized.includes("messaging")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-09"]!;
    }
    if (normalized.includes("saga") || normalized.includes("outbox")) return DESIGNED_TO_SCALE_SCENARIOS["java-10"]!;
    if (normalized.includes("jwt") || normalized.includes("oauth")) return DESIGNED_TO_SCALE_SCENARIOS["java-11"]!;
    if (normalized.includes("cqrs")) return DESIGNED_TO_SCALE_SCENARIOS["java-a02"]!;
    if (normalized.includes("opentelemetry") || normalized.includes("causal span")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-12"]!;
    }
    if (normalized.includes("testcontainers") || normalized.includes("kim tự tháp")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-a01"]!;
    }
    if (normalized.includes("liveness") || normalized.includes("readiness") || normalized.includes("prr")) {
      return DESIGNED_TO_SCALE_SCENARIOS["java-a03"]!;
    }
  }
  const modCode = (modulePosition && MODULE_DEFAULT_CODES[modulePosition]) || "java-f01";
  return DESIGNED_TO_SCALE_SCENARIOS[modCode] ?? DESIGNED_TO_SCALE_SCENARIOS["java-f01"]!;
}
