export function matchQuizQuestionsForItem(modulePosition: number, title?: string | null): QuizQuestionData[] {
  const byPos = JAVA_COURSERA_MODULES.find((m) => m.position === modulePosition);
  const quizItem = byPos?.items.find((i) => i.type === "QUIZ");
  if (quizItem?.quizQuestions?.length) {
    return quizItem.quizQuestions;
  }
  const byTitle = JAVA_COURSERA_MODULES.find((m) =>
    title ? title.toLowerCase().includes(`chương ${m.position}`) || m.labTitle.toLowerCase() === title.toLowerCase() : false,
  );
  return byTitle?.items.find((i) => i.type === "QUIZ")?.quizQuestions ?? JAVA_COURSERA_MODULES[0]?.items[3]?.quizQuestions ?? [];
}

/**
 * Merges live backend assignments/roadmap labs into the static 6-Module catalog
 * when the backend course authoring draft/published snapshot has not yet populated modules,
 * ensuring the full 6-chapter syllabus is always browseable in both Lecturer and Student UI.
 */
export function buildCourseraModulesWithLabLinks(
  assignments: Array<{ id: string; title: string; labOrder?: number | null | undefined }>,
  roadmapLabs: Array<{ assignmentId: string; position: number; title: string; state: string }>,
): OutlineModuleData[] {
  return JAVA_COURSERA_MODULES.map((mod) => {
    const matchedAssignment =
      assignments.find((a) => a.labOrder === mod.position || a.title === mod.labTitle) ??
      roadmapLabs.find((l) => l.position === mod.position || l.title === mod.labTitle);
    const linkedAssignmentId =
      matchedAssignment && "assignmentId" in matchedAssignment
        ? matchedAssignment.assignmentId
        : matchedAssignment?.id ?? null;

    return {
      ...mod,
      items: mod.items.map((item) =>
        item.type === "QUIZ" || item.type === "STATIC_LAB" || item.type === "IMPACT_LAB" || item.type === "RUNTIME_LAB"
          ? { ...item, assignmentId: linkedAssignmentId }
          : item,
      ),
    };
  });
}
