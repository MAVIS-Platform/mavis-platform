package com.mavis.workerclient;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.sun.net.httpserver.HttpServer;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.time.*;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicReference;
import static org.junit.jupiter.api.Assertions.*;
import static com.mavis.workerclient.WorkerContract.*;

class ClientContractTest {
    @TempDir Path temp;
    private final ObjectMapper json = new ObjectMapper();
    private static final String KEY = "fixture-only-not-for-production-32-byte-key";
    private byte[] resource(String name) throws Exception { try (var input = getClass().getResourceAsStream("/fixtures/" + name)) { assertNotNull(input); return input.readAllBytes(); } }
    private Context context(Instant deadline) throws Exception {
        var claims = json.readTree(resource("claims.json"));
        return new Context("p", "s", "j", "a1", claims.get("artifactId").asText(), claims.get("expectedInputDigest").asText(), deadline);
    }
    private Clock fixtureClock() { return Clock.fixed(Instant.parse("2026-10-21T11:59:00Z"), ZoneOffset.UTC); }

    @Test void producerFixtureIsReadAndTamperingIsRejected() throws Exception {
        Result result = json.readValue(resource("result.json"), Result.class); Context scope = context(Instant.parse("2026-10-21T12:00:00Z"));
        ResultValidator.validate(result, scope);
        var invalid = json.readTree(resource("result.json")); ((com.fasterxml.jackson.databind.node.ObjectNode)invalid).put("attemptId", "another-attempt");
        assertThrows(IllegalArgumentException.class, () -> ResultValidator.validate(json.treeToValue(invalid, Result.class), scope));
        var corrupted = json.readTree(resource("result.json")); ((com.fasterxml.jackson.databind.node.ObjectNode)corrupted.get("canonical").get("evidence").get(0)).put("fileHash", "a".repeat(64));
        assertThrows(IllegalArgumentException.class, () -> ResultValidator.validate(json.treeToValue(corrupted, Result.class), scope));
    }

    @Test void snapshotFingerprintAndAtomicStagingMatchProducer() throws Exception {
        Path snapshots = Files.createDirectory(temp.resolve("snapshots")); Path source = Files.createDirectory(snapshots.resolve("one")); Path artifacts = Files.createDirectory(temp.resolve("artifacts"));
        Files.write(source.resolve("App.cs"), resource("source/App.cs")); Files.write(source.resolve("App.csproj"), resource("source/App.csproj"));
        var prepared = new SharedArtifactStager(snapshots, artifacts).prepare(source);
        assertEquals(context(Instant.now()).expectedInputDigest(), prepared.manifest().digest());
        assertTrue(prepared.manifest().hasDotnet()); assertTrue(prepared.artifactId().matches("[0-9a-f]{64}"));
        assertEquals(prepared.manifest(), InputFingerprint.inspect(artifacts.resolve(prepared.artifactId())));
        Path ignored = Files.createDirectory(source.resolve("obj")); Files.writeString(ignored.resolve("Ignore.cs"), "class Ignore {}");
        assertEquals(prepared.manifest().digest(), InputFingerprint.inspect(source).digest());
        assertThrows(java.io.IOException.class, () -> new SharedArtifactStager(snapshots, artifacts).prepare(temp));
    }

    @Test void bomDecodedTextAndGeneratedFilesFollowProducerFingerprintPolicy() throws Exception {
        Path source = Files.createDirectory(temp.resolve("source")); Files.writeString(source.resolve("App.csproj"), "<Project />");
        String code = "// tiếng Việt\r\nclass App {}\r\n";
        Files.write(source.resolve("App.cs"), code.getBytes(StandardCharsets.UTF_8)); String plain = InputFingerprint.inspect(source).digest();
        byte[] bytes = code.getBytes(StandardCharsets.UTF_8), bom = new byte[bytes.length + 3]; bom[0]=(byte)239; bom[1]=(byte)187; bom[2]=(byte)191; System.arraycopy(bytes,0,bom,3,bytes.length);
        Files.write(source.resolve("App.cs"), bom); assertEquals(plain, InputFingerprint.inspect(source).digest());
        Files.writeString(source.resolve("Generated.g.cs"), "// <auto-generated />"); assertNotEquals(plain, InputFingerprint.inspect(source).digest());
    }

    @Test void realTransportUsesScopedRouteAuthenticationAndBodyAndPreservesOutcome() throws Exception {
        var server = HttpServer.create(new java.net.InetSocketAddress("127.0.0.1",0),0); var received = new AtomicReference<String>();
        server.createContext("/api/v1/dotnet/analyze", exchange -> {
            try {
                assertEquals("test-service-key", exchange.getRequestHeaders().getFirst("X-Mavis-Worker-Key"));
                received.set(new String(exchange.getRequestBody().readAllBytes(), StandardCharsets.UTF_8));
                byte[] response = resource("result.json"); exchange.getResponseHeaders().add("Content-Type","application/json"); exchange.sendResponseHeaders(200,response.length); exchange.getResponseBody().write(response);
            } catch (Exception e) { throw new RuntimeException(e); } finally { exchange.close(); }
        }); server.start();
        try {
            var clock = fixtureClock(); var client = new ScopedWorkerClient(java.net.URI.create("http://127.0.0.1:"+server.getAddress().getPort()), "test-service-key", new ArtifactGrantIssuer("test",KEY,clock),clock);
            var outcome = client.analyze(context(clock.instant().plusSeconds(25)));
            assertEquals(Status.COMPLETED,outcome.status()); assertNotNull(outcome.result());
            var body = json.readTree(received.get()); assertEquals(2,body.size()); assertFalse(body.has("extractedSourcePath"));
            var claims = json.readTree(java.util.Base64.getUrlDecoder().decode(body.get("artifactGrant").asText().split("\\.")[1]));
            assertEquals("a1", claims.get("attemptId").asText()); assertEquals("mavis-worker-analysis",claims.get("audience").asText());
        } finally { server.stop(0); }
    }

    @Test void stalledBodyCannotOutliveDeadline() throws Exception {
        var server = HttpServer.create(new java.net.InetSocketAddress("127.0.0.1",0),0); var executor = Executors.newCachedThreadPool(); server.setExecutor(executor);
        server.createContext("/api/v1/dotnet/analyze", exchange -> {
            try { exchange.sendResponseHeaders(200,0); exchange.getResponseBody().write('{'); exchange.getResponseBody().flush(); Thread.sleep(5000); }
            catch (Exception ignored) {} finally { exchange.close(); }
        }); server.start();
        try {
            Clock clock = Clock.systemUTC(); var client = new ScopedWorkerClient(java.net.URI.create("http://127.0.0.1:"+server.getAddress().getPort()), "test-service-key",new ArtifactGrantIssuer("test",KEY,clock),clock);
            long start=System.nanoTime(); var result=client.analyze(context(clock.instant().plusMillis(100)));
            assertEquals(Status.TIMED_OUT,result.status()); assertTrue(Duration.ofNanos(System.nanoTime()-start).toSeconds()<4);
        } finally { server.stop(0); executor.shutdownNow(); }
    }

    @Test void expiredAndUnavailableAreNotSuccessfulEmptyResults() throws Exception {
        Clock clock=Clock.systemUTC(); var client=new ScopedWorkerClient(java.net.URI.create("http://127.0.0.1:1"),"test-service-key",new ArtifactGrantIssuer("test",KEY,clock),clock);
        assertEquals(Status.TIMED_OUT,client.analyze(context(clock.instant().minusSeconds(1))).status());
        var failed=client.analyze(context(clock.instant().plusSeconds(2))); assertEquals(Status.FAILED,failed.status()); assertNull(failed.result());
    }

    @Test void sharedUnicodeBomAndCrlfCasesMatchDotnetProducer() throws Exception {
        try (var stream = getClass().getResourceAsStream("/fingerprint/cases.json")) {
            for (var scenario : json.readTree(stream)) {
                Path root=Files.createDirectory(temp.resolve(scenario.get("name").asText()));
                for (var file:scenario.get("files")) {
                    Path path=root.resolve(file.get("path").asText()); Files.createDirectories(path.getParent());
                    Files.write(path,java.util.Base64.getDecoder().decode(file.get("contentBase64").asText()));
                }
                assertEquals(scenario.get("expectedDigest").asText(),InputFingerprint.inspect(root).digest());
            }
        }
    }

    @Test void largeBodyAndHttpRejectionsNeverBecomeSuccessfulEmptyResults() throws Exception {
        var status = new java.util.concurrent.atomic.AtomicInteger(200);
        var server=HttpServer.create(new java.net.InetSocketAddress("127.0.0.1",0),0);
        server.createContext("/api/v1/dotnet/analyze",e->{ byte[] data="x".repeat(512).getBytes(StandardCharsets.UTF_8); e.sendResponseHeaders(status.get(),data.length); e.getResponseBody().write(data);e.close(); });server.start();
        try {
            var clock=fixtureClock();var issuer=new ArtifactGrantIssuer("test",KEY,clock);var url=java.net.URI.create("http://127.0.0.1:"+server.getAddress().getPort());
            var client=new ScopedWorkerClient(url,"test-service-key",issuer,clock,java.net.http.HttpClient.newHttpClient(),16);
            assertEquals("RESULT_TOO_LARGE",client.analyze(context(clock.instant().plusSeconds(25))).code());
            client=new ScopedWorkerClient(url,"test-service-key",issuer,clock);
            for(int code:new int[]{401,403,408,429,500}) {
                status.set(code);var outcome=client.analyze(context(clock.instant().plusSeconds(25)));
                assertNotEquals(Status.COMPLETED,outcome.status());assertNull(outcome.result());
            }
        }finally{server.stop(0);}
    }
}
