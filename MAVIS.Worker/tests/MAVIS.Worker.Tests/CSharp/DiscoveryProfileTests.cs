using MAVIS.Worker.Application.Analysis;
using MAVIS.Worker.Infrastructure.CSharp;
using Microsoft.Extensions.Options;

namespace MAVIS.Worker.Tests.CSharp;

public sealed class DiscoveryProfileTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "mavis-discovery-" + Guid.NewGuid().ToString("N"));
    private void Write(string name, string content) { var path = Path.Combine(_root, name); Directory.CreateDirectory(Path.GetDirectoryName(path)!); File.WriteAllText(path, content); }
    private Task<DotnetAnalysisResult> Analyze(bool generated = true) => new DotnetProjectAnalyzer(Options.Create(new DotnetAnalysisOptions
        { AllowedSourceRoots = [_root], ExcludeGeneratedSources = generated })).AnalyzeAsync(new("p", "s", _root, "j"), CancellationToken.None);

    [Fact]
    public async Task NestedProjectsOwnTheirDefaultSourceAndNearestConfig()
    {
        Write("Root.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        Write("src/Orders/Orders.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        Write("src/Orders/Order.cs", "class Order {}");
        Write("src/Orders/config/appsettings.json", """{"PaymentUrl":"http://localhost:5002"}""");
        var result = await Analyze();
        var type = Assert.Single(result.Findings.Where(f => f.Kind == "Type"));
        Assert.Equal("src/Orders/Orders.csproj", type.ProjectPath);
        var project = Assert.Single(result.Projects!.Where(p => p.ProjectPath == type.ProjectPath));
        Assert.Equal("src/Orders", project.RootPath); Assert.Equal("Orders", project.Name);
        Assert.Contains(result.Findings, f => f.Kind == "ConfigurationHttpReference" && f.ProjectPath == type.ProjectPath && f.Target == "localhost:5002");
    }

    [Fact]
    public async Task GeneratedPolicyIsExplicitAndDoesNotChangeInputFingerprint()
    {
        Write("App.csproj", "<Project />"); Write("A.g.cs", "class Generated {}");
        Write("B.cs", "// <auto-generated />\nclass OtherGenerated {}"); Write("User.cs", "class User {}");
        var excluded = await Analyze(); var included = await Analyze(false);
        Assert.Equal(excluded.InputDigest, included.InputDigest);
        Assert.Equal(1, excluded.Coverage.AnalyzedFiles); Assert.Equal(3, included.Coverage.AnalyzedFiles);
        Assert.Equal(2, excluded.Warnings.Count(w => w.Code == "GENERATED_SOURCE_EXCLUDED"));
    }

    [Fact]
    public async Task ConfigurationVariantsRemainAmbiguousAndExternalReferencesAreNotOpened()
    {
        Write("App.csproj", "<Project><ItemGroup><ProjectReference Include=\"../outside.csproj\" /><ProjectReference Include=\"missing.csproj\" /></ItemGroup></Project>");
        Write("appsettings.json", """{"PaymentUrl":"http://localhost:5001"}""");
        Write("appsettings.Development.json", """{"PaymentUrl":"http://localhost:5002"}""");
        var result = await Analyze();
        Assert.Contains(result.Findings, f => f.Kind == "ProjectReferenceCandidate" && f.ResolutionStatus == "External" && f.Target is null);
        Assert.Contains(result.Findings, f => f.Kind == "ProjectReferenceCandidate" && f.ResolutionStatus == "Unresolved");
        Assert.Contains(result.Findings, f => f.Kind == "ConfigurationHttpReference" && f.ResolutionStatus == "Ambiguous" && f.Target is null && f.AdditionalEvidence!.Count == 1);
        Assert.Contains(result.Warnings, w => w.Code == "AMBIGUOUS_CONFIGURATION_REFERENCE");
    }
    public void Dispose() { if (Directory.Exists(_root)) Directory.Delete(_root, true); }
}
